import { readdirSync, readFileSync, writeFileSync, statSync } from 'node:fs'

const root = new URL('../src/programs/', import.meta.url)
const esc = s => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;')
const rows = []
let count = 0

for (const folder of readdirSync(root).sort()) {
	if (!statSync(new URL(folder, root)).isDirectory()) continue
	let first = true
	for (const file of readdirSync(new URL(folder + '/', root)).filter(f => f.endsWith('.js')).sort()) {
		const src = readFileSync(new URL(folder + '/' + file, root), 'utf8')
		const tag = t => {
			const m = src.match(new RegExp('^@' + t + '[ \\t]+(.+)$', 'm'))
			return m ? esc(m[1].trim()) : ''
		}
		const name = file.slice(0, -3)
		// The author only for programs that are not mine
		const by = folder == 'contributed' && tag('author') ? ' by ' + tag('author') : ''
		rows.push('\t\t<div class="folder">' + (first ? folder : '') + '</div>'
			+ '<a href="run.html?' + folder + '/' + name + '">' + name + '</a>'
			+ '<div>' + tag('title') + '</div>'
			+ '<div>' + tag('desc') + by + '</div>')
		first = false
		count++
	}
}

const page = `<!DOCTYPE html>
<html lang="en">
<head>
	<meta charset="utf-8">
	<title>Directory</title>
	<link rel="stylesheet" type="text/css" href="../css/simple_console.css">
	<style type="text/css" media="screen">
		body {
			margin: 2em;
			font-family: 'Simple Console', monospace;
			line-height: 1.2;
		}
		.list {
			display: grid;
			grid-template-columns: auto auto auto 1fr;
			row-gap: 0.2em;
			column-gap: 3ch;
		}
		.folder {
			color: black;
		}
		a {
			color: royalblue;
			text-decoration: none;
		}
		a:hover {
			text-decoration: underline;
		}
	</style>
</head>
<body>
	<!-- Generated by tools/directory.js (npm run list) -->
	<div class="list">
` + rows.join('\n') + `
	</div>
</body>
</html>
`

// Run with: npm run list
writeFileSync(new URL('../pages/directory.html', import.meta.url), page)
console.log('directory.html: ' + count + ' programs')
